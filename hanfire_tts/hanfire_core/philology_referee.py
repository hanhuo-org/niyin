def check_qieyun_plausibility(oc_ipa: str, mc_ipa: str) -> Tuple[float, List[str]]:
    """
    检验候选上古音 `oc_ipa` 顺推至《切韵》`mc_ipa` 的音理合理性得分 (0..1) 与诊断说明。
    """
    if not oc_ipa or not mc_ipa:
        return 0.6, []
    oc = parse_mononuclear_4slot(oc_ipa)
    mc = parse_mononuclear_4slot(mc_ipa)
    score = 1.0
    notes: List[str] = []

    # 1. 拦截极端声母违逆（如 MC 晓/心/生母 x/s/ʃ，OC 却拟成鼻音 n/ŋ；MC 影母 ʔ，OC 却拟成 l）
    if mc.onset in ("x", "h", "s", "ʃ", "ʂ", "ts", "t͡s", "tsʰ", "t͡sʰ") and oc.onset in ("n", "ŋ", "m"):
        score -= 0.65
        notes.append(f"声母违逆《切韵》({oc.onset} 难变 {mc.onset})")
    if mc.onset in ("ʔ", "") and oc.onset == "l" and mc.nucleus == "i":
        score -= 0.45
        notes.append("影母四等拟边音 l 违背直觉听感")

    # 2. 拦截晚起六朝舌面腭化声母倒灌上古（钱大昕“古无舌上、章系归端定”）
    if oc.onset in PALATAL_LATE_ONSETS:
        score -= 0.30
        notes.append(f"晚起舌面音({oc.onset})倒灌上古，宜归舌尖/齿音或泥母")

    # 3. 拦截王力二等麻/陌/肴生造双元音 ea (kea, beak)
    if "ea" in oc_ipa:
        score -= 0.25
        notes.append("含生造双元音 ea，二等古本为纯洪音 a")

    # 4. 拦截《诗经》真部 -n 误拟为 -ŋ (如 人 niŋ vs MC ɲʑien)
    if mc.coda == "n" and oc.coda == "ŋ":
        score -= 0.45
        notes.append("《切韵》-n 尾且《诗经》押真部，不宜拟 -ŋ")

    return max(0.0, score), notes


